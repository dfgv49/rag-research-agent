"""State management for the researcher graph.

This module defines the state structures used in the researcher graph.
"""

from dataclasses import dataclass, field
from typing import Annotated, Any, Literal, Optional, Union

from langchain_core.documents import Document
from langchain_core.messages import AnyMessage

from shared.state import reduce_docs


class ReplaceDocuments(list):
    """标记「这份文档列表要整体替换，而不是合并」。

    合并语义（下面的 reducer）是「新来的排前面、旧的补齐」，它能让并行分支正常
    汇入、也能让 rerank 改顺序，但**没法让 rerank 丢掉落选文档**——被丢掉的文档会
    作为「旧文档」被补回末尾，于是 top_n 形同虚设（实测：重排后 5 篇，状态里仍有
    6 篇）。rerank 节点因此用这个轻量标记包一层，reducer 见到它就整体替换。
    （同一个思路见 langgraph 的 `add_messages` + `RemoveMessage`。）
    """


def reduce_rerankable_docs(
    existing: Optional[list[Document]],
    new: Union[
        list[Document],
        list[dict[str, Any]],
        list[str],
        str,
        Literal["delete"],
    ],
) -> list[Document]:
    """合并检索结果，并允许**后写入方决定顺序**（rerank 节点需要）。

    为什么不能直接用 `shared.state.reduce_docs`：它是纯追加语义——保留 `existing`
    的原顺序、只把没见过的文档接到末尾。并行检索分支汇入时这样正好，但 rerank 节点
    返回的是「同一批文档的新顺序」，追加语义会把它悄悄丢掉（所有 uuid 都已在
    existing 里，最终顺序仍是重排前的）。

    这里改成：本次写入的文档按**它给的顺序**排在前面，落选的旧文档保持原顺序接在
    后面；文档身份仍是 `metadata["uuid"]`（= md5(page_content)），所以任何一篇都
    不会重复出现。并行分支的合并顺序本来就是任意的，因此这个改动对它们没有影响。

    若 `new` 是 `ReplaceDocuments`，则整体替换（rerank 用它来真正丢掉落选文档）。

    Args:
        existing: 当前状态里的文档列表。
        new: 本次节点写入的文档（支持 Document / dict / str 以及 "delete"）。

    Returns:
        list[Document]: 合并后的有序文档列表。
    """
    if isinstance(new, str) and new == "delete":
        return []
    if isinstance(new, ReplaceDocuments):
        return list(new)
    existing_list = list(existing) if existing else []
    # 复用 shared 的实现做归一化（dict/str -> Document）与批内去重。
    incoming = reduce_docs([], new)
    if not incoming:
        return existing_list
    incoming_ids = {document.metadata.get("uuid") for document in incoming}
    leftover = [
        document
        for document in existing_list
        if document.metadata.get("uuid") not in incoming_ids
    ]
    return incoming + leftover


@dataclass(kw_only=True)
class QueryState:
    """Private state for the retrieve_documents node in the researcher graph."""

    query: str


@dataclass(kw_only=True)
class ResearcherState:
    """State of the researcher graph / agent."""

    question: str
    """A step in the research plan generated by the retriever agent."""
    history: list[AnyMessage] = field(default_factory=list)
    """Recent conversation turns handed down by the main graph.

    Used only by `rewrite_query` to resolve pronouns/ellipsis in follow-up
    questions ("那它和边有什么区别？" is unsearchable on its own). The main graph
    already truncates this window; an empty list means "no rewrite needed".
    """
    rewritten_question: str = ""
    """The self-contained search query produced by `rewrite_query`.

    Empty when the node was skipped or produced nothing; `generate_queries`
    falls back to `question` in that case.
    """
    queries: list[str] = field(default_factory=list)
    """A list of search queries based on the question that the researcher generates."""
    documents: Annotated[list[Document], reduce_rerankable_docs] = field(
        default_factory=list
    )
    """Populated by the retriever, then re-ordered by the `rerank` node.

    The reducer is order-aware (see `reduce_rerankable_docs`) because the parallel
    branches only have to append, while rerank has to be able to re-order.
    """
    rerank_applied: bool = False
    """Whether the `rerank` node actually re-ordered `documents`.

    False means the candidates kept their fused order — either rerank is disabled or
    the rerank call failed (the reason is in `rerank_error`).
    """
    rerank_error: str = ""
    """Reason the rerank call degraded, empty when it succeeded or was disabled."""

